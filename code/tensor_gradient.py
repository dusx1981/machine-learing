"""
================================================================================
PyTorch 自动微分与梯度下降
================================================================================
功能：使用PyTorch的autograd机制实现梯度下降优化

核心概念：
    - requires_grad=True：标记需要计算梯度的张量
    - backward()：反向传播，计算所有requires_grad=True的参数的梯度
    - grad：张量的梯度值，存储在 .grad 属性中
    - detach()：从计算图中分离，用于从GPU转到CPU或转numpy
    - no_grad()：禁用梯度计算，节省内存和计算

注意事项：
    1. 每个迭代后需要清空梯度（zero_grad()），否则梯度会累积
    2. 使用 .data 或 .detach() 修改张量值，避免追踪历史
    3. backward() 只能对标量调用，否则需要传入 grad_parameters
    4. 梯度会累积，适合mini-batch训练
================================================================================
"""

import torch


def f(x, y):
    """
    目标函数：f(x, y) = x² + y²

    参数:
        x: 第一个自变量张量
        y: 第二个自变量张量

    返回:
        函数值

    说明:
        这是一个简单的凸函数，最小值在 (0, 0) 处
    """
    return x*x + y*y


if __name__ == '__main__':
    # ================================================================================
    # 初始化参数
    # ================================================================================
    # 创建需要优化的张量，并标记需要计算梯度
    # requires_grad=True 告诉PyTorch需要追踪这个张量的操作历史
    x = torch.tensor([1.1], requires_grad=True)
    y = torch.tensor([2.1], requires_grad=True)

    # 优化超参数
    alpha = 0.05  # 学习率
    n = 200       # 迭代次数

    print("开始梯度下降优化...")
    print("=" * 60)

    # ================================================================================
    # 梯度下降迭代
    # ================================================================================
    for i in range(1, n + 1):
        # 1. 前向传播：计算函数值
        z = f(x, y)

        # 2. 反向传播：计算梯度
        # backward() 计算 z 关于所有 requires_grad=True 的张量的梯度
        z.backward()

        # 3. 手动梯度更新（不使用优化器）
        # 使用 .data 属性获取内部数据，避免追踪梯度
        # 重要：必须使用 -= 而不是 =，以保持计算图连接
        x.data -= alpha * x.grad.data
        y.data -= alpha * y.grad.data

        # 4. 清空梯度，为下一次迭代做准备
        # 重要：如果不清空，梯度会累积！
        x.grad.zero_()
        y.grad.zero_()

        # 每20次迭代打印一次结果
        if i % 20 == 0 or i == 1:
            print(
                f'第 {i:3d} 次迭代: '
                f'x = {x.item():.4f}, '
                f'y = {y.item():.4f}, '
                f'f(x,y) = {z.item():.4f}'
            )

    print("=" * 60)
    print(f'最优解: x* = {x.item():.6f}, y* = {y.item():.6f}')
    print(f'理论最优解: x* = 0, y* = 0')

