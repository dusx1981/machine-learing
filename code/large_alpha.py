"""
================================================================================
学习率过大导致梯度爆炸示例
================================================================================
功能：演示学习率选择不当导致的数值发散问题

原理：
    当学习率 α 过大时，梯度更新可能跳过最优解，导致参数在极值点附近震荡
    极端情况下，参数会指数级增长，导致数值溢出(NaN)

数学分析：
    目标函数：f(x) = x² - 2x + 3
    梯度：f'(x) = 2x - 2
    更新规则：x_{k+1} = x_k - α * f'(x_k) = x_k - α(2x_k - 2)

    当 α > 1 时，更新方程 x_{k+1} = (1-2α)x_k + 2α 的系数 |1-2α| > 1
    导致参数发散

注意事项：
    1. 学习率应该通过实验调整，通常从较小的值开始
    2. 监控损失函数或参数值，及时发现发散迹象
    3. 数值溢出(NaN)是不可逆的，需要重新初始化参数
    4. 实践中可以使用学习率衰减、Adam等自适应方法
================================================================================
"""

# ================================================================================
# 参数初始化
# ================================================================================
# 初始点
x = 20

# 学习率设置过大（正常情况应远小于1）
alpha = 100

# 最大迭代次数
round = 10

# ================================================================================
# 迭代过程（演示发散）
# ================================================================================
for i in range(1, round + 1):
    # 计算梯度：f'(x) = 2x - 2
    gradient = 2 * x - 2

    # 更新参数
    step = alpha * gradient
    x = x - step

    # 计算当前函数值
    fx = x**2 - 2 * x + 3

    print(
        f'After {i}, '
        f'x = {x: .3f}, '
        f'f(x) = {fx: .3f}'
    )

# 观察结果：
#   - 第1次迭代后，x 从 20 变为 -3780（跳过了原点）
#   - 后续迭代中，x 的绝对值指数级增长
#   - 第3次迭代后，数值已溢出为 inf/-inf
#   - 最终结果为 NaN（Not a Number）

# ================================================================================
# 如何避免梯度爆炸
# ================================================================================
"""
1. 学习率衰减：
   alpha = initial_alpha / (1 + decay_rate * epoch)

2. 使用自适应优化器：
   - Adam：自动调整每个参数的学习率
   - RMSprop：对梯度进行归一化
   - Adagrad：对频繁更新的参数使用更小的学习率

3. 梯度裁剪（Gradient Clipping）：
   - 将梯度的范数限制在某个范围内
   - torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm)

4. 权重初始化：
   - Xavier初始化：适合tanh/sigmoid
   - He初始化：适合ReLU
"""

