"""
================================================================================
PyTorch 自动微分演示
================================================================================
功能：使用PyTorch的autograd机制自动计算函数 f(x) = x² + 3x + 2 的导数

核心概念：
    - requires_grad：标记需要计算梯度的张量
    - backward()：自动反向传播计算梯度
    - detach()：从计算图分离，转为普通张量
    - torch.no_grad()：临时禁用梯度计算

注意事项：
    1. backward() 只能对标量调用，对张量调用需要先求和
    2. detach() 创建新张量，不共享梯度信息
    3. 转换numpy前必须detach，否则会报错
    4. 梯度累积：多次backward会累加梯度，需要手动清零
================================================================================
"""

import torch
import matplotlib.pyplot as plt


def f(x):
    """
    目标函数：f(x) = x² + 3x + 2

    参数:
        x: PyTorch张量

    返回:
        函数值张量
    """
    return x*x + 3*x + 2


if __name__ == '__main__':
    # ================================================================================
    # 生成自变量序列
    # ================================================================================
    # linspace: 创建等间隔的张量
    # requires_grad=True: 标记需要计算梯度
    x = torch.linspace(-6.5, end=3.5, steps=1000, requires_grad=True)

    # 前向传播
    y_f = f(x)

    # ================================================================================
    # 反向传播计算梯度
    # ================================================================================
    # 注意：backward() 只能对标量调用
    # 对向量调用时，需要先求和转换为标量
    y_f.sum().backward()

    # 提取梯度：x.grad 存储了 df/dx 的值
    y_df = x.grad

    # ================================================================================
    # 转换为NumPy绘图
    # ================================================================================
    # 注意：需要先detach()，否则无法转为numpy
    # - detach(): 从计算图分离，不追踪梯度
    # - numpy(): 转为numpy数组

    # 验证：df/dx = 2x + 3
    # 当 x = 0 时，梯度应为 3
    # 当 x = -1.5 时，梯度应为 0（极值点）

    y_f_np = y_f.detach().numpy()
    y_df_np = y_df.detach().numpy()
    x_np = x.detach().numpy()

    # ================================================================================
    # 可视化
    # ================================================================================
    plt.figure(figsize=(10, 6))
    plt.plot(x_np, y_f_np, label='f(x) = x² + 3x + 2', linewidth=2)
    plt.plot(x_np, y_df_np, label="f'(x) = 2x + 3", linewidth=2)

    # 标记极值点
    plt.axhline(y=0, color='gray', linestyle='--', alpha=0.5)
    plt.axvline(x=-1.5, color='red', linestyle=':', alpha=0.7,
                label='极值点 x = -1.5')

    plt.xlabel('x')
    plt.ylabel('y')
    plt.legend()
    plt.grid(True, alpha=0.3)
    plt.title('PyTorch自动微分示例')
    plt.show()

# ================================================================================
# 补充说明
# ================================================================================
"""
1. 为什么需要 y_f.sum().backward() 而不是 y_f.backward()？
   - PyTorch的autograd设计为对标量进行反向传播
   - 对于向量，需要先聚合为一个标量（如求和）

2. 为什么需要detach()？
   - detach() 创建张量的新副本，不参与梯度追踪
   - 用于将GPU张量转为CPU张量，或转为numpy
   - 不detach直接转numpy会报错

3. 关于梯度累积：
   - 多次调用backward()会累积梯度
   - 需要时应该使用 x.grad.data.zero_() 清零
   - 这是实现梯度累积（gradient accumulation）的基础
"""