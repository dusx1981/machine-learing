"""
================================================================================
手动计算函数导数示例
================================================================================
功能：绘制函数 f(x) = x² + 3x + 2 及其导数 f'(x) = 2x + 3 的图像

数学原理：
    - 函数在某点的导数表示该点切线的斜率
    - 导数大于0：函数递增；导数小于0：函数递减
    - 导数等于0：可能是极值点

注意事项：
    1. 导数公式需要手动推导，可能出错
    2. 对于复杂函数，手动求导容易遗漏
    3. 实际应用中推荐使用自动微分工具（如PyTorch、TensorFlow）
================================================================================
"""

import numpy as np
import matplotlib.pyplot as plt

# ================================================================================
# 定义目标函数及其导数
# ================================================================================

def f(x):
    """
    目标函数：f(x) = x² + 3x + 2

    参数:
        x: 自变量，可以是标量或数组

    返回:
        函数值
    """
    return x**2 + 3*x + 2


def df(x):
    """
    目标函数的导数：f'(x) = 2x + 3

    推导过程：
        d/dx(x²) = 2x
        d/dx(3x) = 3
        d/dx(2) = 0

    参数:
        x: 自变量，可以是标量或数组

    返回:
        导数值
    """
    return 2*x + 3


if __name__ == '__main__':
    # 生成x轴数据点
    x = np.linspace(-6.5, 3.5, 1000)

    # 计算函数值和导数值
    y_f = f(x)
    y_df = df(x)

    # 绘制图像
    plt.figure(figsize=(10, 6))
    plt.plot(x, y_f, label='f(x) = x² + 3x + 2', linewidth=2)
    plt.plot(x, y_df, label="f'(x) = 2x + 3", linewidth=2)

    # 标记零点
    plt.axhline(y=0, color='gray', linestyle='--', alpha=0.5)
    plt.axvline(x=0, color='gray', linestyle='--', alpha=0.5)

    plt.legend()
    plt.xlabel('x')
    plt.ylabel('y')
    plt.grid(True, alpha=0.3)
    plt.title('函数及其导数可视化')
    plt.show()

# 图像分析：
#   - 抛物线 f(x) 开口向上，顶点在 x = -1.5 处
#   - 导数 f'(x) = 2x + 3 是直线，在 x = -1.5 处穿过零点
#   - 零点位置对应原函数的极值点