"""
================================================================================
梯度下降算法 - 基础示例
================================================================================
功能：使用梯度下降算法求解二元函数 f(x, y) = x² + y² 的最小值

原理：
    梯度下降通过迭代更新参数来最小化目标函数：
        θ = θ - α * ∇f(θ)
    其中 α 是学习率，∇f(θ) 是目标函数的梯度

注意事项：
    1. 学习率(α)选择至关重要：
       - 太小：收敛速度慢
       - 太大：可能跳过最优解甚至发散
    2. 目标函数 f(x,y) = x² + y² 的梯度为 [2x, 2y]
    3. 初始点 (2.1, 1.1) 在函数图像的右侧，梯度指向原点
================================================================================
"""

# ================================================================================
# 初始化参数
# ================================================================================
# 初始位置：从任意点开始迭代
x = 2.1
y = 1.1

# 最大迭代次数
n = 100

# 学习率(learning rate)：控制每一步的步长
# 重要：学习率需要根据目标函数的特性调整
alpha = 0.05  # 对于 f(x,y)=x²+y²，0.05 是合适的学习率

# ================================================================================
# 梯度下降迭代
# ================================================================================
for i in range(1, n + 1):
    # 计算梯度：目标函数 f(x,y) = x² + y² 的梯度为 ∇f = [∂f/∂x, ∂f/∂y] = [2x, 2y]
    gx = 2 * x  # ∂f/∂x
    gy = 2 * y  # ∂f/∂y

    # 更新参数：沿梯度负方向移动
    x = x - alpha * gx
    y = y - alpha * gy

    # 打印当前迭代结果
    print(
        f'After {i}, '
        f'x = {x: .3f}, '
        f'y = {y: .3f}, '
        f'f(x, y) = {x**2 + y**2: .3f}'
    )

# 收敛分析：
#   - 理论最优解：(0, 0)
#   - 收敛速度取决于学习率和初始点
#   - 由于梯度随接近最优解而减小，步长自动调整